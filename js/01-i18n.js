  const map = { 'zh-TW': 'tw', 'zh-CN': 'cn', 'en': 'en' };
  let lang = 'zh-TW';

  const I18n = {
    get lang() { return lang; },
    get languages() { return ['zh-TW', 'zh-CN', 'en']; },
    setLang(next, silent) {
      if (!D[next]) next = 'zh-TW';
      lang = next;
      document.body.dataset.lang = next;
      document.documentElement.lang = next === 'zh-TW' ? 'zh-Hant' : next === 'zh-CN' ? 'zh-Hans' : 'en';
      I18n.applyDOM();
      if (!silent) RL.Bus.emit('lang:change', next);
      if (RL.Save && RL.Save.data) { RL.Save.data.profile.lang = next; RL.Save.queue(); }
      if (RL.UI && RL.UI.refreshMenu) RL.UI.refreshMenu();
    },
    t(key, vars) {
      const table = D[lang] || D['zh-TW'];
      let s = table[key];
      if (s == null) s = (D['zh-TW'][key] != null ? D['zh-TW'][key] : key);
      if (vars) for (const k in vars) s = s.replace(new RegExp('\\{' + k + '\\}', 'g'), String(vars[k]));
      return s;
    },
    name(obj) {
      if (!obj) return '';
      return obj[map[lang]] || obj.tw || obj.en || '';
    },
    applyDOM(root) {
      (root || document).querySelectorAll('[data-i18n]').forEach(el => {
        const k = el.getAttribute('data-i18n');
        const val = I18n.t(k);
        if (el.dataset.keepHtml === '1') el.innerHTML = val; else el.textContent = val;
      });
      (root || document).querySelectorAll('[data-i18n-title]').forEach(el => {
        el.title = I18n.t(el.getAttribute('data-i18n-title'));
        el.setAttribute('aria-label', el.title);
      });
    }
  };
